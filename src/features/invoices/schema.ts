import { z } from "zod";
import { currencyCodeSchema } from "@/features/currencies/schema";
import { MAX_EXPENSE_ITEMS } from "@/features/transactions/breakdown-summary";
import { expectedUnitsSchema } from "@/lib/currency-intent";
import { MAX_MINOR } from "@/lib/money";

/** Folder names. */
export const MAX_NAME = 60;
/** Row names: long enough for a full product title. */
export const MAX_ITEM_NAME = 200;
export const MAX_CATEGORY_NAME = 40;
export const MAX_PERSON_NAME = 30;
export const MAX_FOLDERS = 100;
export const MAX_ITEMS = 500;
export const MAX_CATEGORIES = 30;
/** A row's quantity: a whole number of units, each at the row's price. */
export const MAX_QUANTITY = 9999;
export const MAX_GUESTS = 20;
/** Rows paid together become one expense whose breakdown lists them, so one currency's rows share the breakdown cap. */
export const MAX_PAY_ITEMS = MAX_EXPENSE_ITEMS;
/** One payment may cover this many currencies (one expense each). */
export const MAX_PAY_CURRENCIES = 8;

const name = z.string().trim().min(1).max(MAX_NAME);
const itemName = z.string().trim().min(1).max(MAX_ITEM_NAME);
const categoryName = z.string().trim().min(1).max(MAX_CATEGORY_NAME);
const price = z.number().int().min(1).max(MAX_MINOR);
const decimalPlaces = z.number().int().min(0).max(8);
const quantity = z.number().int().min(1).max(MAX_QUANTITY);
/** The row total (price x quantity) stays inside the money range, like a price on its own. */
const totalInRange = (value: { priceMinor: number; quantity: number }) => value.priceMinor * value.quantity <= MAX_MINOR;
const totalMessage = { message: "price x quantity is out of range", path: ["quantity"] };

/** `id` is generated by the form so a retried save can never create a second folder. */
export const folderCreateSchema = z.strictObject({ id: z.uuid(), name });
export const folderRenameSchema = z.strictObject({ name });

/** Same idea for categories: the sheet picks the id so a retry never makes a second one. */
export const categoryCreateSchema = z.strictObject({ id: z.uuid(), folderId: z.uuid(), name: categoryName });
export const categoryRenameSchema = z.strictObject({ name: categoryName });

/** The row keeps the decimals it was priced with, so a later change to a viewer's catalog never reinterprets it. */
export const itemCreateSchema = z.strictObject({
  expectedUnits: expectedUnitsSchema.optional(),
  id: z.uuid(), folderId: z.uuid(), categoryId: z.uuid(), name: itemName,
  currency: currencyCodeSchema, decimalPlaces, priceMinor: price, quantity,
}).refine(totalInRange, totalMessage);
export const itemEditSchema = z.strictObject({
  name: itemName, priceMinor: price, quantity, categoryId: z.uuid().optional(),
  currency: currencyCodeSchema.optional(), decimalPlaces: decimalPlaces.optional(),
}).refine((value) => (value.currency === undefined) === (value.decimalPlaces === undefined), {
  message: "currency and decimalPlaces change together",
  path: ["decimalPlaces"],
}).refine(totalInRange, totalMessage);

const uniqueIds = (max: number) => z.array(z.uuid()).min(1).max(max).refine((ids) => new Set(ids).size === ids.length);

/** Bulk actions on ticked rows: one call for the whole batch. */
export const itemsDeleteSchema = z.strictObject({ folderId: z.uuid(), itemIds: uniqueIds(MAX_ITEMS) });
export const itemsMoveSchema = z.strictObject({ folderId: z.uuid(), itemIds: uniqueIds(MAX_ITEMS), categoryId: z.uuid() });
export const itemsRestoreSchema = z.strictObject({ itemIds: uniqueIds(MAX_ITEMS) });

/**
 * Paying rows: one expense per currency, each from a balance of that currency (never mixed or
 * converted). Every `requestId` is generated by the sheet and becomes that expense's id, so a
 * retried save can never record a payment twice. `categoryId` is one of the payer's own
 * expense categories, not a folder category.
 */
export const itemsPaySchema = z.strictObject({
  expectedUnits: expectedUnitsSchema,
  folderId: z.uuid(), categoryId: z.uuid(),
  occurredOn: z.iso.date().refine((value) => value >= "2000-01-01"),
  payments: z.array(z.strictObject({ requestId: z.uuid(), balanceId: z.uuid(), itemIds: uniqueIds(MAX_PAY_ITEMS) })).min(1).max(MAX_PAY_CURRENCIES),
}).refine((value) => {
  const requests = value.payments.map((payment) => payment.requestId);
  const items = value.payments.flatMap((payment) => payment.itemIds);
  return new Set(requests).size === requests.length && new Set(items).size === items.length;
}, { message: "a row or a request appears twice", path: ["payments"] });

export const personNameSchema = z.string().trim().min(1).max(MAX_PERSON_NAME);
export const tokenSchema = z.string().regex(/^[0-9a-f]{64}$/);

export type FolderCreateInput = z.infer<typeof folderCreateSchema>;
export type CategoryCreateInput = z.infer<typeof categoryCreateSchema>;
export type ItemCreateInput = z.infer<typeof itemCreateSchema>;
export type ItemEditInput = z.infer<typeof itemEditSchema>;
export type ItemsDeleteInput = z.infer<typeof itemsDeleteSchema>;
export type ItemsMoveInput = z.infer<typeof itemsMoveSchema>;
export type ItemsRestoreInput = z.infer<typeof itemsRestoreSchema>;
export type ItemsPayInput = z.infer<typeof itemsPaySchema>;

/** What a batch answers with for each row that is still there (server clock). */
export type SavedRow = { id: string; updatedAt: string };
export type RestoredRow = SavedRow & { createdAt: string };
/** A row's paid marker as the database reported it. */
export type PaidRow = SavedRow & { paidOn: string; paidAt: string };

/** A saved row's timestamps as the database reported them (server clock, never the device's). */
export type SavedTimes = { createdAt: string; updatedAt: string };

/** `isDefault` marks "Other": every folder has exactly one, and it can be neither renamed nor deleted. */
export type InvoiceCategory = { id: string; folderId: string; name: string; isDefault: boolean; createdAt: string };

export type InvoiceItem = {
  id: string; folderId: string; categoryId: string; name: string; currency: string; decimalPlaces: number;
  /** The price of ONE unit; the row's total is `priceMinor * quantity` (see `lineMinor`). */
  priceMinor: number; quantity: number;
  createdBy: string | null; createdAt: string; updatedAt: string;
  /**
   * Set only while the expense that paid this row is live in the payer's Activity: its date,
   * and when the row was marked. `paidBy` is null for a payer whose account is gone.
   * Nothing about the payer's wallet or the expense itself is ever here.
   */
  paidOn: string | null; paidAt: string | null; paidBy: string | null;
};
export type InvoiceMember = {
  userId: string; displayName: string | null; isOwner: boolean; joinedAt: string; removed: boolean;
};
/** `minor` is null when the sum would leave the safe integer range. */
export type CurrencyTotal = { currency: string; decimalPlaces: number; minor: number | null };
export type InvoiceFolderSummary = {
  id: string; name: string; isOwner: boolean; memberCount: number; itemCount: number; totals: CurrencyTotal[];
};
