import { z } from "zod";
import { currencyCodeSchema } from "@/features/currencies/schema";
import { MAX_QUANTITY } from "@/features/invoices/schema";
import { MAX_EXPENSE_ITEMS } from "@/features/transactions/breakdown-summary";
import { expectedUnitsSchema } from "@/lib/currency-intent";
import { MAX_MINOR } from "@/lib/money";

export const MAX_ITEM_NAME = 60;
/** One purchase becomes one expense whose breakdown lists the items, so it shares the breakdown cap. */
export const MAX_BUY_ITEMS = MAX_EXPENSE_ITEMS;

/** Moving rows into an invoice folder is one statement, so it shares the folder's own row cap's order of magnitude. */
export const MAX_MOVE_ITEMS = 100;
/** "Delete selected" is one statement; the cap matches the database function's own. */
export const MAX_DELETE_ITEMS = 500;

const name = z.string().trim().min(1).max(MAX_ITEM_NAME);
const price = z.number().int().min(1).max(MAX_MINOR);
/** How many units, each at the item's price: the same rule as an invoice row's quantity. */
const quantity = z.number().int().min(1).max(MAX_QUANTITY);
/** The item total (price x quantity) stays inside the money range, like a price on its own. */
const totalInRange = (value: { priceMinor: number; quantity: number }) => value.priceMinor * value.quantity <= MAX_MINOR;
const totalMessage = { message: "price x quantity is out of range", path: ["quantity"] };
const date = z.iso.date().refine((value) => value >= "2000-01-01");

/** `id` is generated by the form so a retried save can never create a second item. */
export const itemCreateSchema = z.strictObject({
  expectedUnits: expectedUnitsSchema.optional(),
  id: z.uuid(), name, currency: currencyCodeSchema, priceMinor: price, quantity,
}).refine(totalInRange, totalMessage);
export const itemEditSchema = z.strictObject({ expectedUnits: expectedUnitsSchema.optional(), name, priceMinor: price, quantity }).refine(totalInRange, totalMessage);
export const itemBuySchema = z.strictObject({
  expectedUnits: expectedUnitsSchema.optional(),
  requestId: z.uuid(),
  itemIds: z.array(z.uuid()).min(1).max(MAX_BUY_ITEMS).refine((ids) => new Set(ids).size === ids.length),
  balanceId: z.uuid(), categoryId: z.uuid(), occurredOn: date,
});

/**
 * Items become rows of an invoice folder (same ids, so a retry after a lost response is a no-op).
 * `expectedUnits` is required: each row keeps the decimals it was priced with.
 */
export const itemMoveSchema = z.strictObject({
  expectedUnits: expectedUnitsSchema,
  folderId: z.uuid(),
  itemIds: z.array(z.uuid()).min(1).max(MAX_MOVE_ITEMS).refine((ids) => new Set(ids).size === ids.length),
});

/** "Delete selected": every ticked item goes in one statement. */
export const itemDeleteSchema = z.strictObject({
  itemIds: z.array(z.uuid()).min(1).max(MAX_DELETE_ITEMS).refine((ids) => new Set(ids).size === ids.length),
});

export type ItemCreateInput = z.infer<typeof itemCreateSchema>;
export type ItemMoveInput = z.infer<typeof itemMoveSchema>;
export type ItemEditInput = z.infer<typeof itemEditSchema>;
export type ItemBuyInput = z.infer<typeof itemBuySchema>;
export type ItemDeleteInput = z.infer<typeof itemDeleteSchema>;

export type ShoppingItem = {
  id: string; name: string; currency: string;
  /** The price of ONE unit; the item's total is `priceMinor * quantity` (see `lineMinor`). */
  priceMinor: number; quantity: number; createdAt: string;
  /** Set only while the purchase is live in Activity. */
  boughtOn: string | null; transactionId: string | null;
};
